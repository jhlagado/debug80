#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import {
  assembleAtomProject,
  renderAtomArtifacts,
} from "atom-z80";
import {
  normalizeZ80AssemblerFlavour,
  Z80_ASSEMBLER_FLAVOUR,
} from "@jhlagado/z80-tool-services";

const repositoryRoot = path.resolve(
  fileURLToPath(new URL("..", import.meta.url)),
);
const check = process.argv.slice(2).includes("--check");
const fixtures = [
  {
    directory: "apps/debug80-vscode/tests/e2e/fixtures/simple",
    target: "app",
  },
  {
    directory: "apps/debug80-vscode/tests/e2e/fixtures/dap-source-maps",
    target: "include-app",
  },
  {
    directory: "apps/debug80-vscode/tests/e2e/fixtures/dap-source-maps",
    target: "sparse-org",
  },
];

function contentBase(generation) {
  const addresses = generation.images.map(({ address }) => address);
  for (const event of generation.layout ?? []) {
    if (event.kind === "reserve" && event.count !== 0)
      addresses.push(event.address);
  }
  return addresses.length === 0
    ? generation.finalCursor
    : Math.min(...addresses);
}

async function writeOrCheck(filename, content) {
  if (check) {
    const existing = await fs.readFile(filename);
    if (!existing.equals(Buffer.from(content))) {
      throw new Error(
        `${path.relative(repositoryRoot, filename)} is not generated by Atom`,
      );
    }
    return;
  }
  const temporary = `${filename}.tmp`;
  await fs.mkdir(path.dirname(filename), { recursive: true });
  await fs.writeFile(temporary, content);
  await fs.rename(temporary, filename);
}

for (const fixture of fixtures) {
  const root = path.join(repositoryRoot, fixture.directory);
  const configuration = JSON.parse(
    await fs.readFile(path.join(root, ".vscode", "debug80.json"), "utf8"),
  );
  const target = configuration.targets?.[fixture.target];
  if (
    normalizeZ80AssemblerFlavour(target?.assembler, {
      defaultFlavour: Z80_ASSEMBLER_FLAVOUR.auto,
    }) !== Z80_ASSEMBLER_FLAVOUR.atom
  ) {
    throw new Error(`${fixture.directory}#${fixture.target} must select Atom`);
  }
  const result = await assembleAtomProject({
    root,
    entry: target.sourceFile,
    assembler: target.assembler,
    target: { start: 0, capacity: 0xffff },
  });
  const base = contentBase(result.generation);
  const entryAddress = target.simple?.entry ?? base;
  const artifacts = renderAtomArtifacts(result, { base, entryAddress });
  const artifactRoot = path.join(root, target.outputDir ?? "build");
  await writeOrCheck(path.join(root, target.hex), artifacts.hex);
  await writeOrCheck(
    path.join(artifactRoot, `${target.artifactBase}.d8.json`),
    artifacts.d8Text,
  );
  process.stdout.write(
    `${check ? "Checked" : "Generated"} ${fixture.directory}#${fixture.target}\n`,
  );
}
